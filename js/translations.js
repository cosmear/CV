// `const` en el scope global NO crea propiedad en window, y main.js busca
// window.TRANSLATIONS para los mensajes del Signal Lab. Se expone explícito.
window.TRANSLATIONS = TRANSLATIONS;

function getPreferredLanguage() {
  const urlParams = new URLSearchParams(window.location.search);
  const urlLang = urlParams.get("lang");
  if (urlLang && TRANSLATIONS[urlLang]) return urlLang;

  const storedLang = localStorage.getItem("lang");
  if (storedLang && TRANSLATIONS[storedLang]) return storedLang;

  const browserLang = (navigator.language || "").slice(0, 2).toLowerCase();
  if (TRANSLATIONS[browserLang]) return browserLang;

  return "es";
}

function updateLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;

  localStorage.setItem("lang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
      el.innerHTML = TRANSLATIONS[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
      el.placeholder = TRANSLATIONS[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-label");
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
      el.setAttribute("aria-label", TRANSLATIONS[lang][key]);
    }
  });

  document
    .querySelectorAll(".translate-es-btn")
    .forEach((btn) => btn.classList.toggle("hidden", lang === "es"));
  document
    .querySelectorAll(".translate-en-btn")
    .forEach((btn) => btn.classList.toggle("hidden", lang === "en"));
}

document.addEventListener("DOMContentLoaded", () => {
  const initialLang = getPreferredLanguage();
  updateLanguage(initialLang);
});
